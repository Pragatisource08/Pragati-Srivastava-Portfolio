export const ROWS = 7;
export const SPACE_COLS = 4; // word space, including the glyph gaps on either side

export type Word = { cols: number; pixels: [number, number][] };

const cache = new Map<string, Word>();

export function layoutWord(word: string): Word {
  const key = word.toUpperCase();
  const hit = cache.get(key);
  if (hit) return hit;
  const pixels: [number, number][] = [];
  let x = 0;
  const chars = [...key];
  chars.forEach((ch, i) => {
    const glyph = G[ch] ?? G["?"];
    const w = glyph[0].length;
    glyph.forEach((row, y) => {
      for (let c = 0; c < w; c++) if (row[c] === "#") pixels.push([x + c, y]);
    });
    x += w + (i < chars.length - 1 ? 1 : 0);
  });
  const out = { cols: x, pixels };
  cache.set(key, out);
  return out;
}

export function lineCols(text: string): number {
  const words = text.split(/\s+/).filter(Boolean);
  return words.reduce((s, w) => s + layoutWord(w).cols, 0) + SPACE_COLS * Math.max(0, words.length - 1);
}

// 4x4 ordered-dither (Bayer) thresholds, used to "develop" a word pixel by pixel.
export const BAYER4 = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
];

export const BAYER8 = (() => {
  const m: number[][] = [];
  for (let y = 0; y < 8; y++) {
    m.push([]);
    for (let x = 0; x < 8; x++) {
      const q = BAYER4[y % 4][x % 4];
      const s = [0, 2, 3, 1][(y >> 2) * 2 + (x >> 2)];
      m[y].push(q * 4 + s);
    }
  }
  return m;
})();
